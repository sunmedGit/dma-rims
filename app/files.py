"""Where uploaded files are kept.

Two implementations behind one protocol: the local filesystem for development
and tests, and a Unity Catalog Volume for the deployed app. Keeping the
protocol means the intake route never cares which it is talking to.

Uploaded forms and approval evidence are company records. Paths are generated
here rather than taken from the client, so a filename can never traverse out of
the configured root.
"""

from __future__ import annotations

import logging
import re
import unicodedata
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional, Protocol

log = logging.getLogger(__name__)

MAX_UPLOAD_BYTES = 15 * 1024 * 1024


class FileTooLarge(ValueError):
    pass


class FileStoreError(RuntimeError):
    pass


def safe_name(filename: str, fallback: str = "upload.bin") -> str:
    """Reduce a client-supplied filename to something safe to put in a path.

    Only the basename survives, accents are folded, and anything outside a
    conservative character set becomes an underscore. A name that reduces to
    nothing becomes the fallback.
    """
    base = Path(filename or "").name
    base = unicodedata.normalize("NFKD", base).encode("ascii", "ignore").decode("ascii")
    base = re.sub(r"[^A-Za-z0-9._-]+", "_", base).strip("._")
    if not base or base in (".", ".."):
        return fallback
    return base[:120]


def generate_path(category: str, filename: str) -> str:
    """A unique, date-partitioned path RELATIVE to the store's root.

    The root belongs to the store, not to the path. Having it in both is how
    uploads ended up under _local_files/_local_files.
    """
    stamp = datetime.now(timezone.utc)
    return "/".join(
        [
            category,
            stamp.strftime("%Y/%m"),
            "%s-%s" % (uuid.uuid4().hex[:12], safe_name(filename)),
        ]
    )


class FileStore(Protocol):
    def write(self, path: str, data: bytes) -> str:
        ...

    def read(self, path: str) -> bytes:
        ...


class LocalFileStore:
    """Development and tests. Writes under a directory on disk."""

    def __init__(self, root: Path):
        self._root = Path(root)

    def _resolve(self, path: str) -> Path:
        # paths are generated by generate_path, but confirm anyway
        target = (self._root / path.lstrip("/")).resolve()
        root = self._root.resolve()
        if root not in target.parents and target != root:
            raise FileStoreError("Refusing to write outside the storage root.")
        return target

    def write(self, path: str, data: bytes) -> str:
        target = self._resolve(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        return str(target)

    def read(self, path: str) -> bytes:
        return self._resolve(path).read_bytes()


class VolumeFileStore:
    """Unity Catalog Volume, through the Databricks Files API.

    NOT yet exercised against a real workspace.
    """

    def __init__(self, root: str, workspace_client=None):
        self._root = root.rstrip("/")
        self._client = workspace_client

    def _get_client(self):
        if self._client is None:
            from databricks.sdk import WorkspaceClient

            self._client = WorkspaceClient()
        return self._client

    def _full(self, path: str) -> str:
        return path if path.startswith(self._root) else self._root + "/" + path.lstrip("/")

    def write(self, path: str, data: bytes) -> str:
        import io

        target = self._full(path)
        try:
            self._get_client().files.upload(target, io.BytesIO(data), overwrite=False)
        except Exception as exc:
            raise FileStoreError("Could not write to the volume: %s" % exc) from exc
        return target

    def read(self, path: str) -> bytes:
        try:
            response = self._get_client().files.download(self._full(path))
            return response.contents.read()
        except Exception as exc:
            raise FileStoreError("Could not read from the volume: %s" % exc) from exc


def check_size(data: bytes, limit: int = MAX_UPLOAD_BYTES) -> bytes:
    if len(data) > limit:
        raise FileTooLarge(
            "That file is %.1f MB; the limit is %.0f MB."
            % (len(data) / 1048576, limit / 1048576)
        )
    return data


def build_file_store(evidence_volume: str, local_root: Optional[Path] = None) -> FileStore:
    """A Volume store when one is configured, otherwise local disk."""
    if evidence_volume.startswith("/Volumes/"):
        return VolumeFileStore(evidence_volume)
    root = local_root or Path(evidence_volume or "./_local_files")
    log.warning("No Unity Catalog Volume configured; storing uploads under %s", root)
    return LocalFileStore(root)
